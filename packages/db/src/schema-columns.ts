type Affinity<S> = [NonNullable<S>] extends [string]
  ? "TEXT"
  : [NonNullable<S>] extends [number]
    ? "INTEGER" | "REAL"
    : never;

/** One column as PRAGMA table_info reports it. The types force it to agree with schema.ts. */
export interface ColSpec<V> {
  readonly type: Affinity<SelectType<V>>;
  readonly notnull: null extends SelectType<V> ? false : true;
  /** 1-based position in the primary key. */
  readonly pk?: number;
}

/** Every table and column in DB: a missing column or a wrong nullability fails tsc. */
export type ColumnMap = {
  readonly [T in keyof DB]: {
    readonly [C in keyof DB[T]]-?: ColSpec<DB[T][C]>;
  };
};

