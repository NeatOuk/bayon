// Invariant 8: a directive to the model belongs to the versioned template, where a version and a
// hash pin it. This sentence was built by string interpolation in the supervisor, so editing it
// changed what the agent was told with no version bump and no hash change — and this file still
// passed. Keeping it here is what makes that impossible.
test("handoff_request.v2: the boundary sentence is the template's own, and takes only two names", () => {
  const boundary = TEMPLATES.handoff_request.sections.find(
    (s) => s.name === "boundary",
  );
  expect(boundary?.text).toBe(
    "This ticket has moved on from {{from}} work to {{to}}. Your successor is a new {{to}} " +
      "session with a different prompt and no memory of this one: write for it. Say what it " +
      "needs to start, not where you stopped.",
  );
  // Only the two run-class names vary: no other slot, so no other wording can come from a caller.
  expect(
    [
      ...new Set(
        [...(boundary?.text ?? "").matchAll(/\{\{(\w+)\}\}/g)].map(
          ([, s]) => s,
        ),
      ),
    ].toSorted(),
  ).toEqual(["from", "to"]);
});

test("build.v8: the builder merges its base before review and before a fix's resubmit, lints last, and never pushes", () => {
  const { body, version } = TEMPLATES.build;
  expect(version).toBe(8);
  for (const rule of [
    // a fix session runs this template, and its move is resubmit, not request_review.
    "Before you request review, or resubmit after a fix, bring your branch up to date with the ticket's base branch",
    "`git fetch origin <base>` then `git merge FETCH_HEAD`",
    "rerun the repo's install, build, lint and test commands, commit, and only then request review or resubmit",
    "Before you resubmit, call finding_resolve on each open finding you fixed.",
    // the prompt half of the lint_check gate. The server decides (§10.3), but a builder
    // that is told the gate exists takes the cheap path and never reaches it.
    "Run the repository's lint command last, on the commit you are asking to have reviewed",
    "a review round runs it as a gate of its own",
    "Never push.",
  ]) {
    expect(body).toContain(rule);
  }
  const merge = body.indexOf("git merge FETCH_HEAD");
  expect(merge).toBeLessThan(body.indexOf("rerun the repo's"));
  expect(body.indexOf("rerun the repo's")).toBeLessThan(
    body.indexOf("only then request review"),
  );
  // Lint is the last thing before the review, so the merge cannot invalidate it.
  expect(body.indexOf("only then request review")).toBeLessThan(
    body.indexOf("Run the repository's lint command last"),
  );
});

