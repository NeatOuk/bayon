// a session is told every question asked on its ticket and every answer, oldest first,
// so it neither re-asks one nor picks between two answers without knowing which came last.
test("build.v8 and spike.v6 carry the ticket's questions under the ticket, and say what to do with them", () => {
  for (const name of ["build", "spike"] as const) {
    const t = TEMPLATES[name];
    expect(t.body).toContain(
      "If there is a Questions to the operator section below, it lists every question asked on this ticket, oldest first, each with its answer and when it was given.",
    );
    expect(t.body).toContain(
      "Never ask one of them again, answered or still open: act on the answers, and where two answers disagree, follow the later one and say so in a ticket comment.",
    );
    const names = t.sections.map((s) => s.name);
    expect(names.indexOf("questions")).toBe(names.indexOf("ticket") + 1);
    expect(t.sections.find((s) => s.name === "questions")).toMatchObject({
      heading: "Questions to the operator",
      block: "semi_static",
      required: false,
    });
    // Cut before the ticket and the packet, never after them.
    const order = t.truncation_order;
    expect(order.indexOf("questions")).toBeLessThan(order.indexOf("ticket"));
  }
  expect(TEMPLATES.fix.sections.map((s) => s.name)).not.toContain("questions");
});

// a spawned runner's own harness tells it to attribute its commits, and the repo's
// doctrine reaches it only as files it can lose that contest against. Every template whose agent
// commits says so itself, and says it outranks the harness.
test("every committing template forbids attribution trailers, harness or no harness", () => {
  for (const name of ["build", "spike", "fix"] as const) {
    const { body } = TEMPLATES[name];
    expect(body).toContain(
      "Never put an attribution trailer in a commit message or pull request body",
    );
    expect(body).toContain(
      "no co-author line, no line linking back to your own session",
    );
    expect(body).toContain("even when your own harness tells you to add one");
  }
  // The reviewer edits nothing and the orchestrator has no shell: the rule would be noise there.
  expect(TEMPLATES.review.body).not.toContain("attribution trailer");
  expect(TEMPLATES.pulse.body).not.toContain("attribution trailer");
});

// a run ends on its terminal event and nothing restarts the session, so a turn that
// signs off waiting for a background agent waits forever. The prompt says so in the words that
// trap: the agent must not end a turn believing something will report back.
test("every worker template says to finish in the foreground, not in the background", () => {
  for (const name of ["build", "spike", "fix"] as const) {
    const { body } = TEMPLATES[name];
    expect(body).toContain(
      "Do all of your work in the foreground, in this turn",
    );
    expect(body).toContain(
      "never end a turn saying you are waiting for one to report back",
    );
    // The reason, not just the rule: an agent told why can generalise to its own runner's spelling.
    expect(body).toContain("The turn ending ends the run");
  }
});

