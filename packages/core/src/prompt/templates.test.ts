test("pulse records its closing block's text in section_order_json; other templates are unchanged", async () => {
  const pulse = await templateRecord(TEMPLATES.pulse);
  const order: unknown = JSON.parse(pulse.section_order_json);
  const closing = TEMPLATES.pulse.sections.at(-1);
  expect(closing?.name).toBe("closing");
  expect(Array.isArray(order) ? order.at(-1) : null).toEqual({
    block: "volatile",
    heading: "Before you finish",
    name: "closing",
    required: true,
    text: closing?.text,
  });
  const review = await templateRecord(TEMPLATES.review);
  expect(review.section_order_json).not.toContain('"text"');
});

describe("the schema refuses a malformed template", () => {
  const section = (
    name: string,
    block: PromptBlock,
    extra: { max_tokens?: number } = {},
  ) => ({ name, heading: name, block, required: false, ...extra });
  const base = {
    name: "t",
    version: 1,
    body: "b",
    sections: [section("a", "static")],
    truncation_order: [] as string[],
  };
  const problems = (patch: Partial<typeof base>): string[] => {
    const parsed = PromptTemplate.safeParse({ ...base, ...patch });
    return parsed.success ? [] : parsed.error.issues.map((i) => i.message);
  };

  test("a well-formed one passes", () => {
    expect(problems({})).toEqual([]);
  });

  test.each([
    [
      "a section twice",
      { sections: [section("a", "static"), section("a", "static")] },
      "section a appears twice",
    ],
    [
      "a cut listed twice",
      { truncation_order: ["a", "a"] },
      "truncation_order lists a twice",
    ],
    [
      "a block out of order",
      { sections: [section("a", "volatile"), section("b", "static")] },
      "section b (static) follows a later block",
    ],
    [
      "a cut of no section",
      { truncation_order: ["zz"] },
      "truncation_order names no section zz",
    ],
    [
      "a cap on a section that may not be cut",
      { sections: [section("a", "static", { max_tokens: 100 })] },
      "section a has max_tokens but may not be cut",
    ],
    [
      "a fixed section that may be cut",
      {
        sections: [{ ...section("a", "static"), text: "fixed" }],
        truncation_order: ["a"],
      },
      "section a has fixed text and may not be cut",
    ],
  ])("%s", (_, patch, message) => {
    expect(problems(patch)).toEqual([message]);
  });

  test("a per-section cap has a floor", () => {
    expect(
      problems({
        sections: [section("a", "static", { max_tokens: 15 })],
        truncation_order: ["a"],
      }),
    ).toHaveLength(1);
  });
});
