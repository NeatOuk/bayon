import { describe, expect, test } from "vitest";
import { localTokens } from "../prompt/budget.js";
import { HandoffFacts } from "./facts.js";
import {
  PACKET_TRUNCATION_MARKER,
  renderFacts,
  renderPacket,
  type Judgement,
  type PacketHeader,
} from "./packet.js";

// The packet renderer (App. D).
const facts = (o: Partial<HandoffFacts> = {}): HandoffFacts =>
  HandoffFacts.parse({
    v: 1,
    ticket: { id: "t1", key: "FRM-7", status: "building" },
    session: { id: "s1", role: "builder", run_class: "build" },
    repos: [
      {
        repo_id: "repo",
        branch: "frm/s1",
        base_sha: "a3f19c2aaaaaaaa",
        head_sha: "91bd04ebbbbbbbb",
        commits: 1,
        files: [
          { path: "README.md", code: "M", added: 1, removed: 0 },
          { path: "new.txt", code: "??" },
        ],
      },
    ],
    commands: [{ argv: ["pnpm", "test"], exit_code: 1, status: null }],
    gates: [],
    findings_open: 0,
    questions: [{ id: "hr_1", text: "idempotency table or redis?" }],
    spend: { session_usd: 4.1, ticket_usd: 6.3 },
    counters: {
      turns: 48,
      max_turns: 60,
      tool_calls: 12,
      context_peak_tokens: 17_000,
      context_cap: 25_000,
    },
    events: { first_id: 1420, last_id: 1890 },
    gathered_at: 0,
    ...o,
  });

const header: PacketHeader = {
  key: "FRM-7",
  id: "01M2DST3T87FSWN6EYS71CYRX5",
  n: 3,
  phaseFrom: "build",
  phaseTo: "build",
  reason: "turn_ceiling",
  quality: "full",
};

const judgement: Judgement = {
  goal_line: "Make transfer_request the sole writer path.",
  decisions_md: "- Guard lives in the service.",
  traps_md: "- @Transactional swallows the unique violation.",
  next_steps_md: "1. Catch it.\n2. Fix the fixture.\n3. Re-run the tests.",
  open_questions_md: null,
  pointers: ["plan: docs/spikes/frm-7.md"],
};

const OPTIONS = { verified: true, why: "", capTokens: 1200 };
const bullets = (n: number) =>
  Array.from({ length: n }, (_, i) => `- ${`${i}`.repeat(300)}`).join("\n");

describe("renderPacket", () => {
  test("renders App. D's sections in order, the facts first", () => {
    const { text, truncated } = renderPacket(
      header,
      facts(),
      judgement,
      OPTIONS,
    );
    const headings = text.split("\n").filter((line) => line.startsWith("#"));
    expect(headings).toEqual([
      // The id rides in the header, so a successor can name its hand-off.
      "# Hand-off FRM-7 · handoff-3 (id 01M2DST3T87FSWN6EYS71CYRX5) · build → build · reason: turn_ceiling · quality: full",
      "## Facts (generated by foreman — do not edit)",
      "## Goal (one line)",
      "## Decisions made, and why",
      "## Traps and dead ends (do not repeat)",
      "## Next 3 steps",
      "## Pointers",
    ]);
    expect(text).toContain("M README.md +1 -0 · ?? new.txt");
    expect(text).toContain("base a3f19c2 · head 91bd04e");
    expect(text).toContain("`pnpm test` → exit 1");
    expect(text).toContain('hr_1 ("idempotency table or redis?")');
    expect(text).toContain("$4.10 (session) / $6.30 (ticket) · turns 48/60");
    expect(text).toContain("logs: events 1420–1890");
    expect(truncated).toEqual([]);
  });

  test("is deterministic: the same row gives the same bytes", () => {
    const a = renderPacket(header, facts(), judgement, OPTIONS);
    const b = renderPacket(header, facts(), judgement, OPTIONS);
    expect(a).toEqual(b);
    expect(a.tokens_est).toBe(localTokens(a.text));
  });

  test("a maximal judgement is cut in App. D's order to the cap; goal and next steps stay", () => {
    const big: Judgement = {
      goal_line: "g".repeat(200),
      decisions_md: bullets(6),
      traps_md: bullets(6),
      next_steps_md: bullets(3),
      open_questions_md: bullets(5),
      pointers: Array.from({ length: 10 }, () => "p".repeat(300)),
    };
    const many = facts({
      repos: [
        {
          repo_id: "repo",
          branch: "frm/s1",
          base_sha: "a".repeat(40),
          head_sha: "b".repeat(40),
          commits: 0,
          files: Array.from({ length: 60 }, (_, i) => ({
            path: `src/file-${i}.ts`,
            code: "M",
          })),
        },
      ],
    });
    const p = renderPacket(header, many, big, OPTIONS);
    expect(p.tokens_est).toBeLessThanOrEqual(1200);
    expect(p.truncated.slice(0, 3)).toEqual([
      "pointers",
      "open_questions",
      "files",
    ]);
    expect(p.text).toContain("g".repeat(200));
    expect(p.text).toContain(bullets(3));
    expect(p.text).toContain(PACKET_TRUNCATION_MARKER);
    expect(p.text).toContain("… and 40 more");
  });

  test("more than 40 files end in '… and N more'", () => {
    const files = Array.from({ length: 45 }, (_, i) => ({
      path: `f${i}`,
      code: "??",
    }));
    const f = facts({
      repos: facts().repos.map((repo) => ({ ...repo, files })),
    });
    const { text } = renderPacket(header, f, null, {
      ...OPTIONS,
      verified: false,
      why: "the session died",
    });
    expect(text).toContain("files changed (45): ");
    expect(text).toContain("… and 5 more");
  });

  test("a degraded packet with a judgement renders it under the unverified banner", () => {
    const { text } = renderPacket(
      { ...header, quality: "degraded" },
      facts(),
      judgement,
      { ...OPTIONS, verified: false, why: "the cap hit" },
    );
    expect(text).toContain("## Written before the cap hit — unverified");
    expect(text).toContain("quality: degraded");
    expect(text.indexOf("unverified")).toBeLessThan(text.indexOf("## Goal"));
  });

  test("a degraded packet without a judgement is the facts and one line", () => {
    const { text } = renderPacket(
      { ...header, quality: "degraded" },
      facts({ commands: [], questions: [], repos: [] }),
      null,
      { ...OPTIONS, verified: false, why: "the session died" },
    );
    expect(text.trimEnd().split("\n").at(-1)).toBe(
      "(no judgement: the session died)",
    );
    expect(text).toContain("commands: none recorded");
    expect(text).not.toContain("## Goal");
  });

  test("a git failure is said, not hidden", () => {
    const { text } = renderPacket(
      header,
      facts({ repos: [], git_error: "executor local is not loaded" }),
      null,
      { ...OPTIONS, verified: false, why: "x" },
    );
    expect(text).toContain("git: executor local is not loaded");
  });
});

test("renderFacts is the Facts block without its heading", () => {
  const body = renderFacts(facts());
  expect(body.startsWith("ticket: FRM-7 (building)")).toBe(true);
  expect(body).not.toContain("## ");
});

test("a superproject's submodule HEADs are a line of their own; no line without them", () => {
  expect(renderFacts(facts())).not.toContain("submodules (");
  const body = renderFacts(
    facts({
      repos: [
        {
          repo_id: "super",
          branch: "frm/s1",
          base_sha: "a3f19c2aaaaaaaa",
          head_sha: "91bd04ebbbbbbbb",
          commits: 1,
          files: [],
          submodules: [
            { path: "libs/mid", repo_id: "mid", sha: "c0ffee1aaaaaaaa" },
          ],
        },
      ],
    }),
  );
  expect(body).toContain("submodules (1): libs/mid c0ffee1");
});
