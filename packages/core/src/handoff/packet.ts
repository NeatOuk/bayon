import { localTokens } from "../prompt/budget.js";
import type { HandoffFacts, RepoFacts } from "./facts.js";
import type { HandoffQuality } from "./quality.js";

// The hand-off packet (§7.2, App. D): pure, so the same row always renders the same bytes and
// `packet_hash` can be checked and the file re-created from the row.

export const PACKET_TRUNCATION_MARKER = "[… truncated by foreman]";
export const FACTS_HEADING = "Facts (generated by foreman — do not edit)";

export interface PacketHeader {
  readonly key: string;
  /** The hand-off's id: the header shows it, so a successor can name it. */
  readonly id: string;
  readonly n: number;
  readonly phaseFrom: string;
  readonly phaseTo: string;
  readonly reason: string;
  readonly quality: HandoffQuality;
}

/** The agent-written half, as the API stores it (`handoffs` judgement columns). */
export interface Judgement {
  readonly goal_line: string;
  readonly decisions_md: string | null;
  readonly traps_md: string | null;
  readonly next_steps_md: string | null;
  readonly open_questions_md: string | null;
  readonly pointers: readonly string[];
}

export interface PacketOptions {
  /** True: the judgement is the packet's. False: it renders under an "unverified" banner. */
  readonly verified: boolean;
  /** Why the packet is degraded, e.g. "the cap hit" or "the session died". */
  readonly why: string;
  /** `handoff.packet_tokens_cap`. */
  readonly capTokens: number;
}

export interface Packet {
  readonly text: string;
  readonly tokens_est: number;
  /** The sections cut to meet the cap, in cut order. */
  readonly truncated: readonly string[];
}

/** How much of each cuttable section a render shows. */
interface Shape {
  readonly files: number;
  readonly commands: number;
  readonly pointers: boolean;
  readonly questions: boolean;
  readonly traps: boolean;
  readonly decisions: boolean;
}

const FILES_MAX = 40;
const COMMANDS_MAX = 8;
const FULL: Shape = {
  files: FILES_MAX,
  commands: COMMANDS_MAX,
  pointers: true,
  questions: true,
  traps: true,
  decisions: true,
};

/** App. D's cut order: the goal, the next steps and the facts header are never cut. */
const CUTS: readonly (readonly [string, (s: Shape) => Shape])[] = [
  ["pointers", (s) => ({ ...s, pointers: false })],
  ["open_questions", (s) => ({ ...s, questions: false })],
  ["files", (s) => ({ ...s, files: 20 })],
  ["traps", (s) => ({ ...s, traps: false })],
  ["decisions", (s) => ({ ...s, decisions: false })],
  ["commands", (s) => ({ ...s, commands: 4 })],
];

/** Renders the packet, cutting sections in App. D's order until it fits `capTokens`. */
export function renderPacket(
  header: PacketHeader,
  facts: HandoffFacts,
  judgement: Judgement | null,
  o: PacketOptions,
): Packet {
  let shape = FULL;
  const truncated: string[] = [];
  let text = draw(header, facts, judgement, o, shape, truncated);
  for (const [name, cut] of CUTS) {
    if (localTokens(text) <= o.capTokens) break;
    shape = cut(shape);
    truncated.push(name);
    text = draw(header, facts, judgement, o, shape, truncated);
  }
  return { text, tokens_est: localTokens(text), truncated };
}

/** The Facts block's lines without its heading: the handoff_request prompt's `facts` section. */
export function renderFacts(facts: HandoffFacts): string {
  return factLines(facts, FULL, []).join("\n");
}

function draw(
  h: PacketHeader,
  facts: HandoffFacts,
  j: Judgement | null,
  o: PacketOptions,
  shape: Shape,
  truncated: readonly string[],
): string {
  const lines = [
    `# Hand-off ${h.key} · handoff-${h.n} (id ${h.id}) · ${h.phaseFrom} → ${h.phaseTo} · reason: ${h.reason} · quality: ${h.quality}`,
    `## ${FACTS_HEADING}`,
    ...factLines(facts, shape, truncated),
    ...judgementLines(j, o, shape),
  ];
  return `${lines.join("\n")}\n`;
}

const sha7 = (sha: string | null): string => (sha ?? "?").slice(0, 7);
const usd = (n: number): string => `$${n.toFixed(2)}`;

function factLines(
  f: HandoffFacts,
  shape: Shape,
  truncated: readonly string[],
): string[] {
  const c = f.counters;
  const context =
    c.context_cap === 0
      ? "n/a"
      : `${c.context_peak_tokens ?? "?"}/${c.context_cap}`;
  const logs =
    f.events.first_id === null
      ? "no events"
      : `events ${f.events.first_id}–${f.events.last_id ?? f.events.first_id}`;
  return [
    `ticket: ${f.ticket.key} (${f.ticket.status}) · session: ${f.session.id} (${f.session.role}, ${f.session.run_class})`,
    ...(f.git_error === undefined ? [] : [`git: ${f.git_error}`]),
    ...f.repos.flatMap((r) =>
      repoLines(r, shape.files, truncated.includes("files")),
    ),
    commandLine(f, shape.commands, truncated.includes("commands")),
    f.gates.length === 0
      ? "gates: none"
      : `gates: ${f.gates.map((g) => `${g.kind} ${g.state} (attempt ${g.attempt})`).join(" · ")}`,
    `open findings: ${f.findings_open} · open questions: ${
      f.questions.length === 0
        ? "none"
        : f.questions.map((q) => `${q.id} ("${q.text}")`).join(" · ")
    }`,
    `spend: ${usd(f.spend.session_usd)} (session) / ${usd(f.spend.ticket_usd)} (ticket) · turns ${c.turns}/${c.max_turns} · tool calls ${c.tool_calls} · context ${context} · logs: ${logs}`,
  ];
}

function repoLines(r: RepoFacts, max: number, cut: boolean): string[] {
  const shown = r.files.slice(0, max).map((file) => {
    const counts =
      file.added === undefined ? "" : ` +${file.added} -${file.removed ?? 0}`;
    return `${file.code} ${file.path}${counts}`;
  });
  const more = r.files.length - shown.length;
  const tail = [
    ...(more > 0 ? [`… and ${more} more`] : []),
    ...(cut && more > 0 ? [PACKET_TRUNCATION_MARKER] : []),
  ];
  const subs = r.submodules ?? [];
  return [
    `repo ${r.repo_id}: branch ${r.branch} · base ${sha7(r.base_sha)} · head ${sha7(r.head_sha)} · commits since base: ${r.commits}`,
    ...(r.git_error === undefined ? [] : [`git: ${r.git_error}`]),
    // Each already in its own mirror, so a successor's checkout can reach it.
    ...(subs.length === 0
      ? []
      : [
          `submodules (${subs.length}): ${subs
            .map((s) => `${s.path} ${sha7(s.sha)}`)
            .join(" · ")}`,
        ]),
    `files changed (${r.files.length}): ${
      r.files.length === 0 ? "none" : [...shown, ...tail].join(" · ")
    }`,
  ];
}

function commandLine(f: HandoffFacts, max: number, cut: boolean): string {
  if (f.commands.length === 0) return "commands: none recorded";
  const shown = f.commands.slice(0, max).map((c) => {
    const end =
      c.exit_code !== null ? `exit ${c.exit_code}` : (c.status ?? "unknown");
    return `\`${c.argv.join(" ")}\` → ${end}`;
  });
  const more = f.commands.length - shown.length;
  return `commands: ${[
    ...shown,
    ...(more > 0 ? [`… and ${more} more`] : []),
    ...(cut && more > 0 ? [PACKET_TRUNCATION_MARKER] : []),
  ].join(" · ")}`;
}

function judgementLines(
  j: Judgement | null,
  o: PacketOptions,
  shape: Shape,
): string[] {
  if (j === null) return [`(no judgement: ${o.why})`];
  const section = (heading: string, body: string | null, keep = true) =>
    keep
      ? [
          `## ${heading}`,
          body === null || body.trim() === "" ? "(none)" : body.trimEnd(),
        ]
      : [`## ${heading}`, PACKET_TRUNCATION_MARKER];
  const pointers = j.pointers.map((p) => `- ${p}`).join("\n");
  return [
    ...(o.verified ? [] : [`## Written before ${o.why} — unverified`]),
    ...section("Goal (one line)", j.goal_line),
    ...section("Decisions made, and why", j.decisions_md, shape.decisions),
    ...section("Traps and dead ends (do not repeat)", j.traps_md, shape.traps),
    ...section("Next 3 steps", j.next_steps_md),
    ...(j.open_questions_md === null
      ? []
      : section("Open questions", j.open_questions_md, shape.questions)),
    ...(j.pointers.length === 0
      ? []
      : section("Pointers", pointers, shape.pointers)),
  ];
}
