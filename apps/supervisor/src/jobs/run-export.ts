// The exporter's orchestration (design doc §3): read → render → skip unchanged (by comparing
// bytes, never the DB) → clean up orphans → missions → manifest → git. Pure over injected `deps`,
// so it is fully unit-testable without a database, a filesystem or a git binary; `export-markdown.ts`
// wires the real ones in. `ticket_exports` is never written here (design review point 1): this
// function only produces a manifest, plus whatever git evidence it collected.
import type { Clock } from "@bayon/core";
import { sha256Hex } from "@bayon/core";
import { z } from "zod";
import type { CommitOutcome, EnsureRepoResult, GitStep } from "./git-export.js";
import { EMPTY_MANIFEST, type ExportManifest } from "./manifest.js";
import { findOrphans } from "./orphans.js";
import {
  renderMissionMarkdown,
  renderTicketMarkdown,
  type TicketExportView,
} from "./render.js";

/**
 * `tickets.key_prefix` and a mission's agent name both become path segments (`tickets/<key>.md`,
 * `mission/<agent>/vNN.md`). Both are operator- or agent-controlled strings, not generated by this
 * job, so they are validated here -- the boundary right before they touch a file path -- rather
 * than trusted from upstream: no `.`, `/`, or other separator can smuggle a traversal or an
 * unexpected directory in.
 */
const SafeName = z
  .string()
  .regex(/^[A-Za-z0-9_-]+$/, "must contain only letters, digits, _ or -");

export interface ExportTicket {
  readonly id: string;
  readonly num: number;
  readonly view: Omit<TicketExportView, "key">;
}

export interface ExportMission {
  readonly agentName: string;
  readonly version: number;
  readonly renderedMd: string;
}

export interface ExportFs {
  /** `undefined` if the path does not exist; never throws for a missing file. */
  readonly readFile: (path: string) => Promise<string | undefined>;
  readonly writeFile: (path: string, content: string) => Promise<void>;
  /** `[]` if the directory does not exist. */
  readonly readdir: (path: string) => Promise<readonly string[]>;
  readonly unlink: (path: string) => Promise<void>;
}

export interface ExportDeps {
  readonly listTickets: () => Promise<readonly ExportTicket[]>;
  readonly listMissions: () => Promise<readonly ExportMission[]>;
  readonly fs: ExportFs;
  readonly ensureRepo: (
    repoPath: string,
    clock: Clock,
  ) => Promise<EnsureRepoResult>;
  readonly commit: (
    repoPath: string,
    message: string,
    clock: Clock,
  ) => Promise<
    | { readonly ok: true; readonly value: CommitOutcome }
    | {
        readonly ok: false;
        readonly error: string;
        readonly steps: readonly GitStep[];
      }
  >;
  readonly clock: Clock;
  readonly exportsDir: string;
  readonly keyPrefix: string;
}

export interface ExportResult {
  readonly outcome: "ok" | "failed";
  readonly manifest: ExportManifest;
  readonly gitSteps: readonly GitStep[];
  readonly committed: boolean;
  readonly error?: string;
}

const join = (...parts: readonly string[]): string => parts.join("/");
const ticketKey = (keyPrefix: string, num: number): string =>
  `${keyPrefix}${num}`;

/**
 * Writes every ticket whose rendered bytes differ from what is already on disk (the byte-compare
 * skip: the DB's own `content_hash` is a recorded fact, never the source of truth here -- design
 * review's suggestion), then deletes whatever is on disk but no longer expected (an orphan, most
 * often from a `settings.tickets.key_prefix` change). Returns only what changed this run: an empty
 * manifest is the expected shape of a no-op re-run.
 */
async function writeTickets(
  tickets: readonly ExportTicket[],
  deps: ExportDeps,
): Promise<ExportManifest> {
  SafeName.parse(deps.keyPrefix);
  const ticketsDir = join(deps.exportsDir, "tickets");
  const expected = new Set<string>();
  const entries: ExportManifest["entries"] = [];
  for (const t of tickets) {
    const key = ticketKey(deps.keyPrefix, t.num);
    const fileName = `${key}.md`;
    expected.add(fileName);
    const rendered = renderTicketMarkdown({ ...t.view, key });
    const path = join(ticketsDir, fileName);
    if ((await deps.fs.readFile(path)) === rendered) continue;
    await deps.fs.writeFile(path, rendered);
    entries.push({
      ticket_id: t.id,
      target: "markdown",
      path: join("tickets", fileName),
      content_hash: await sha256Hex(rendered),
    });
  }
  const present = await deps.fs.readdir(ticketsDir);
  const orphans = findOrphans(expected, present);
  for (const name of orphans) await deps.fs.unlink(join(ticketsDir, name));
  return { v: 1, entries, removed: [...orphans] };
}

async function writeMissions(
  missions: readonly ExportMission[],
  deps: ExportDeps,
): Promise<void> {
  for (const m of missions) {
    SafeName.parse(m.agentName);
    const versionTag = `v${String(m.version).padStart(2, "0")}`;
    const dir = join(deps.exportsDir, "mission", m.agentName);
    const path = join(dir, `${versionTag}.md`);
    if ((await deps.fs.readFile(path)) !== undefined) continue; // immutable: written once
    await deps.fs.writeFile(path, renderMissionMarkdown(m.renderedMd));
  }
}

export async function runExport(deps: ExportDeps): Promise<ExportResult> {
  const repo = await deps.ensureRepo(deps.exportsDir, deps.clock);
  if (!repo.ok) {
    return {
      outcome: "failed",
      manifest: EMPTY_MANIFEST,
      gitSteps: [],
      committed: false,
      error: repo.error,
    };
  }

  let manifest: ExportManifest;
  try {
    const [tickets, missions] = await Promise.all([
      deps.listTickets(),
      deps.listMissions(),
    ]);
    manifest = await writeTickets(tickets, deps);
    await writeMissions(missions, deps);
  } catch (e) {
    return {
      outcome: "failed",
      manifest: EMPTY_MANIFEST,
      gitSteps: [],
      committed: false,
      error: e instanceof Error ? e.message : String(e),
    };
  }

  const message = `export: ${manifest.entries.length} ticket(s), ${manifest.removed.length} removed`;
  const committed = await deps.commit(deps.exportsDir, message, deps.clock);
  if (!committed.ok) {
    return {
      outcome: "failed",
      manifest,
      gitSteps: committed.steps,
      committed: false,
      error: committed.error,
    };
  }
  return {
    outcome: "ok",
    manifest,
    gitSteps: committed.value.steps,
    committed: committed.value.committed,
  };
}
